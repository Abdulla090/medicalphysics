import { expect, test } from '@playwright/test';
import { lookAt } from './journey-helpers';

for (const mobile of [false, true]) test(`radiographer calls a waiting patient, registers them at the rear desk and invites escort (${mobile ? 'mobile' : 'desktop'})`, async ({ page }) => {
  if (mobile) await page.setViewportSize({ width: 390, height: 844 });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('language', 'en'));
  await page.goto('/tools/xray-simulator?festival&case=outpatient-chest');
  await page.getByRole('button', { name: 'Begin encounter', exact: true }).click();
  const shell = page.locator('.cg-shell');
  const canvas = page.locator('.sim-three-room canvas');
  await expect(canvas).toHaveAttribute('data-observer-position', /\[/, { timeout: 75000 });
  await expect(shell).toHaveAttribute('data-patient-location', 'waiting');
  const operator = JSON.parse((await canvas.getAttribute('data-observer-position'))!);
  expect(operator[0]).toBeGreaterThan(7.25);
  await lookAt(page, [6.75, 1.34, 4.77]);
  const call = page.getByRole('button', { name: 'Call next patient from waiting' });
  await expect(call).toBeVisible();
  await page.screenshot({ path: `artifacts/simulator/reception-operator-${mobile ? 'mobile' : 'desktop'}.png` });
  await call.click();
  await expect(shell).toHaveAttribute('data-patient-destination', 'reception');
  await expect(shell).toHaveAttribute('data-patient-location', 'reception', { timeout: 90000 });
  await expect(shell).toHaveAttribute('data-patient-destination', '');
  await page.screenshot({ path: `artifacts/simulator/reception-arrived-${mobile ? 'mobile' : 'desktop'}.png` });
  await lookAt(page, [6.75, 1.34, 4.77]);
  await page.getByRole('button', { name: 'Register your patient', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toContainText('Alex Morgan');
  await dialog.getByRole('button', { name: 'Ask full name' }).click();
  await dialog.getByRole('textbox', { name: 'Full name stated by patient' }).fill('Alex Morgan');
  await dialog.getByRole('button', { name: 'Verify against referral' }).first().click();
  await dialog.getByRole('button', { name: 'Ask hospital ID' }).click();
  await dialog.getByRole('textbox', { name: 'Identifier stated by patient' }).fill('EDU 0417');
  await dialog.getByRole('button', { name: 'Verify against referral' }).last().click();
  await dialog.getByRole('button', { name: 'Discuss referral' }).click();
  await dialog.getByRole('button', { name: 'Ask for agreement' }).click();
  await dialog.getByRole('button', { name: 'Complete registration' }).click();
  await expect(shell).toHaveAttribute('data-game-stage', 'changing');
  await expect(shell).toHaveAttribute('data-patient-location', 'reception');
  await lookAt(page, [6.75, 1.34, 4.77]);
  await page.getByRole('button', { name: 'Invite patient to follow' }).click();
  await expect(shell).toHaveAttribute('data-patient-destination', 'changing');
  const dimensions = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
  expect(dimensions.scroll).toBeLessThanOrEqual(dimensions.width + 1);
  expect(errors).toEqual([]);
});
