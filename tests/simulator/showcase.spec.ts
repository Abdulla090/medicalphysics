import { expect, test, type Page } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { lookAt, walkTo } from './journey-helpers';
import { createSession } from '../../src/simulator/session/clinicalSession';
import { getWorldTargets } from '../../src/simulator/worldInteraction';

async function use(page:Page,point:number[],name:string){
  await lookAt(page,point);
  await page.getByRole('button',{name,exact:true}).click();
}
async function review(page:Page){
  await expect(page.getByRole('dialog',{name:'Review the radiograph',exact:true})).toBeVisible({timeout:60000});
  await expect(page.locator('.cg-film canvas')).toHaveAttribute('width','512');
  await page.getByLabel('Coverage observations').fill('The requested anatomy is visible within the field.');
  await page.getByLabel('Positioning observations').fill('The patient is centered without visible rotation.');
  await page.getByLabel('Decision and rationale').fill('Accept this synthetic image after checking alignment and field edges.');
  await page.screenshot({path:'artifacts/simulator/showcase-review.png'});
  await page.getByRole('button',{name:'Accept image',exact:true}).click();
}

